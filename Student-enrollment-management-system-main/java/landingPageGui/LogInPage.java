    private void logInbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_logInbtnActionPerformed
        String username = logInUserNameinputtxt.getText().trim();
        String password = new String(logInPasswordinputtxt.getPassword());

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your username and password.", "Login Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Authenticate directly against the SQL database using LogInService
        String role = logInService.authenticate(username, password);

        if (role == null) {
            failedAttempts++;
            if (failedAttempts >= 3) {
                startLockoutTimer();
            } else {
                int remaining = 3 - failedAttempts;
                JOptionPane.showMessageDialog(
                    this, 
                    "Invalid username or password. " + remaining + " attempt(s) remaining.", 
                    "Login Warning", 
                    JOptionPane.WARNING_MESSAGE
                );
            }
            return;
        }

        failedAttempts = 0;

        // Route user based on role fetched from database
        switch (role) {
            case "Admin" -> {
                String enteredCode = JOptionPane.showInputDialog(
                    this,
                    "Enter Admin Secret Code to proceed:",
                    "Admin Authorization",
                    JOptionPane.QUESTION_MESSAGE
                );

                if (enteredCode == null || !enteredCode.trim().equals(ADMIN_SECRET_CODE)) {
                    JOptionPane.showMessageDialog(this, "Invalid Admin Secret Code! Login aborted.", "Access Denied", JOptionPane.ERROR_MESSAGE);
                    return;
                }

                JOptionPane.showMessageDialog(this, "Login successful! Welcome, " + username + "!", "Login Successful", JOptionPane.INFORMATION_MESSAGE);
                AdminHomePage adminPage = new AdminHomePage(username);
                adminPage.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
                adminPage.setVisible(true);
            }
            case "Teacher" -> {
                JOptionPane.showMessageDialog(this, "Login successful! Welcome, " + username + "!", "Login Successful", JOptionPane.INFORMATION_MESSAGE);
                TeacherHomePage teacherPage = new TeacherHomePage(username);
                teacherPage.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
                teacherPage.setVisible(true);
            }
            case "Student" -> {
                JOptionPane.showMessageDialog(this, "Login successful! Welcome, " + username + "!", "Login Successful", JOptionPane.INFORMATION_MESSAGE);
                StudentHomePage studentPage = new StudentHomePage(username);
                studentPage.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
                studentPage.setVisible(true);
            }
            default -> {
                JOptionPane.showMessageDialog(this, "Unknown account role: " + role, "Login Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        this.dispose();
    }//GEN-LAST:event_logInbtnActionPerformed

