    private void signUpbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_signUpbtnActionPerformed
        String username = signUpUserNameinputtxt.getText().trim();
        String password = new String(signUpPasswordInputtxt.getPassword());
        String confirmPassword = new String(signUpConfirmPasswordinputtxt.getPassword());

        if (username.isEmpty() || password.isEmpty() || confirmPassword.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.", "Sign Up Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!password.equals(confirmPassword)) {
            JOptionPane.showMessageDialog(this, "Passwords do not match.", "Sign Up Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String role = "";
        if (adminSignUpPrevelage.isSelected()) {
            role = "Admin";
        } else if (teacherSignUpPrevelage.isSelected()) {
            role = "Teacher";
        } else if (studentSignUpPrevelage.isSelected()) {
            role = "Student";
        } else {
            JOptionPane.showMessageDialog(this, "Please select an account type.", "Sign Up Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if ("Admin".equals(role)) {
            String enteredCode = JOptionPane.showInputDialog(
                this,
                "Enter the Admin Security Passcode to register as Admin:",
                "Admin Verification",
                JOptionPane.QUESTION_MESSAGE
            );

            if (enteredCode == null || !enteredCode.trim().equals(ADMIN_SECRET_CODE)) {
                JOptionPane.showMessageDialog(this, "Invalid Admin Passcode! You cannot register as an Admin.", "Access Denied", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        // Register user directly into the SQL database through SignUpService
        boolean success = signUpService.registerUser(username, password, role);

        if (success) {
            JOptionPane.showMessageDialog(this, "Account created successfully as " + role + "!", "Success", JOptionPane.INFORMATION_MESSAGE);
            
            switch (role) {
                case "Admin" -> {
                    AdminHomePage adminPage = new AdminHomePage(username);
                    adminPage.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
                    adminPage.setVisible(true);
                }
                case "Teacher" -> {
                    TeacherHomePage teacherPage = new TeacherHomePage(username);
                    teacherPage.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
                    teacherPage.setVisible(true);
                }
                case "Student" -> {
                    StudentHomePage studentPage = new StudentHomePage(username);
                    studentPage.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
                    studentPage.setVisible(true);
                }
            }
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Username already exists. Please choose a different username.", "Registration Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_signUpbtnActionPerformed

