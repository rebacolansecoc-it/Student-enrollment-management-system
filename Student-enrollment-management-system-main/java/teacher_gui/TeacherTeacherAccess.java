    // Purpose: Load teacher assignment details from database and update UI labels and button visibility
    private void loadTeacherAssignmentData() {
        TeacherAssignment ta = teacherService.getAssignmentById(currentTeacherUsername);
        if (ta != null) {
            teacherName.setText(ta.getTeacherName() != null ? ta.getTeacherName() : currentTeacherUsername);
            teacherId.setText(ta.getId() != null ? ta.getId() : currentTeacherUsername);
            autoGeneratedAssignedCourse.setText(ta.getCourse() != null ? ta.getCourse() : "Unassigned");
            submittedEmailAddress.setText(ta.getEmail() != null ? ta.getEmail() : currentTeacherUsername + "@teacher.edu");

            String status = ta.getStatus();
            if ("Status".equalsIgnoreCase(status) || "ASSIGNED".equalsIgnoreCase(status)) {
                assignmentStatus.setText("Assignment Status: Assigned");
                formSubmit.setVisible(false); // Hide button to avoid resubmission once assigned
            } else {
                assignmentStatus.setText("Assignment Status: Waiting to be assign");
                formSubmit.setVisible(true);
                formSubmit.setText("Edit Details"); // Allow editing before assignment
            }
        } else {
            clearDisplay();
        }
    }

    // Purpose: Reset display when no teacher submission exists
    private void clearDisplay() {
        teacherName.setText("Not Submitted");
        teacherId.setText(currentTeacherUsername);
        autoGeneratedAssignedCourse.setText("N/A");
        submittedEmailAddress.setText("N/A");
        assignmentStatus.setText("Assignment Status: Waiting to be assign");
        formSubmit.setVisible(true);
        formSubmit.setText("Form Submit");
    }

    // Purpose: Open dialog box for teacher to submit or edit their assignment request with dynamic course choices from admin
    private void openTeacherSubmissionForm() {
        TeacherAssignment existing = teacherService.getAssignmentById(currentTeacherUsername);

        JTextField nameField = new JTextField(existing != null ? existing.getTeacherName() : currentTeacherUsername);
        JTextField emailField = new JTextField(existing != null ? existing.getEmail() : currentTeacherUsername + "@teacher.edu");

        List<String> courses = teacherService.getAvailableCourses();
        JComboBox<String> courseBox = new JComboBox<>(courses.toArray(new String[0]));
        if (existing != null && existing.getCourse() != null) {
            courseBox.setSelectedItem(existing.getCourse());
        }

        JPanel panel = new JPanel(new java.awt.GridLayout(0, 1, 5, 5));
        panel.add(new JLabel("Teacher ID (Auto-Generated):"));
        JTextField idField = new JTextField(currentTeacherUsername);
        idField.setEditable(false);
        panel.add(idField);
        panel.add(new JLabel("Full Name:"));
        panel.add(nameField);
        panel.add(new JLabel("Email Address:"));
        panel.add(emailField);
        panel.add(new JLabel("Preferred Course:"));
        panel.add(courseBox);

        int result = JOptionPane.showConfirmDialog(this, panel, "Teacher Assignment Form", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (result == JOptionPane.OK_OPTION) {
            String name = nameField.getText().trim();
            String email = emailField.getText().trim();
            String course = (String) courseBox.getSelectedItem();

            if (name.isEmpty() || email.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Name and Email cannot be empty!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            boolean success = teacherService.saveOrUpdateTeacherApplication(currentTeacherUsername, name, email, course);
            if (success) {
                JOptionPane.showMessageDialog(this, "Teacher details saved successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                loadTeacherAssignmentData();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to save teacher details.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

