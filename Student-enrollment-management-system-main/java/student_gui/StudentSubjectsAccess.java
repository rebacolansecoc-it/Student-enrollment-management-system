    // Purpose: Initialize table sorting, selection listeners, and load student enrollment data from MySQL
    private void initStudentCustomLogic() {
        tableModel = (DefaultTableModel) studentSubjectsTbl.getModel();
        rowSorter = new TableRowSorter<>(tableModel);
        studentSubjectsTbl.setRowSorter(rowSorter);

        // Row Selection Listener to dynamically populate Subject Details Panel
        studentSubjectsTbl.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && studentSubjectsTbl.getSelectedRow() != -1) {
                int selectedRow = studentSubjectsTbl.getSelectedRow();
                int modelRow = studentSubjectsTbl.convertRowIndexToModel(selectedRow);

                subjectCode.setText((String) tableModel.getValueAt(modelRow, 0));
                subjectName.setText((String) tableModel.getValueAt(modelRow, 1));
                subjectAssignedTeacherView.setText((String) tableModel.getValueAt(modelRow, 2));
                subjectUnitView.setText(String.valueOf(tableModel.getValueAt(modelRow, 3)));
                subjectCourseView.setText((String) tableModel.getValueAt(modelRow, 4));
            }
        });

        loadStudentEnrollmentCriteria();
        applyFiltersAndSearch();
    }

    // Purpose: Fetch approved student enrollment course and year level criteria from database
    private void loadStudentEnrollmentCriteria() {
        StudentEnrollmentAccessModel enrollment =
                enrollmentService.getEnrollmentByStudentUsername(currentStudentUsername);

        studentIsApproved = enrollment != null && enrollment.isEnrolled();
        enrolledCourse = studentIsApproved ? enrollment.getCourse() : null;
        enrolledYearLevel = studentIsApproved ? enrollment.getGradeLevel() : null;
        enrolledSemester = studentIsApproved ? enrollment.getSemester() : null;
    }

    // Purpose: Load isolated subjects matching student's enrolled course and year level, and apply search filtering
    private void applyFiltersAndSearch() {
        tableModel.setRowCount(0);

        if (studentIsApproved && enrolledCourse != null && enrolledYearLevel != null) {
            List<Subject> studentIsolatedSubjects =
                    SubjectService.getSubjectsForStudent(enrolledCourse, enrolledYearLevel, enrolledSemester);

            if (studentIsolatedSubjects != null) {
                for (Subject s : studentIsolatedSubjects) {
                    tableModel.addRow(new Object[]{
                        s.getSubjectCode(), s.getSubjectTitle(), s.getTeachersDisplay(),
                        s.getUnits(), s.getCoursesDisplay(), s.getYearLevel()
                    });
                }
            }
        }

        String search = searchtxt.getText().trim();
        if (search.isEmpty()) {
            rowSorter.setRowFilter(null);
        } else {
            try {
                rowSorter.setRowFilter(RowFilter.regexFilter("(?i)" + search));
            } catch (java.util.regex.PatternSyntaxException ex) {
                rowSorter.setRowFilter(RowFilter.regexFilter("(?i)" + java.util.regex.Pattern.quote(search)));
            }
        }
    }
