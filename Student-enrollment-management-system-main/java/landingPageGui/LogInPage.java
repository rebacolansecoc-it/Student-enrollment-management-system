    private void startLockoutTimer() {
        logInbtn.setEnabled(false);
        logInbtn.setBackground(java.awt.Color.RED);
        countdownSeconds = 15;
        logInbtn.setText("Wait (" + countdownSeconds + "s)");

        JOptionPane.showMessageDialog(
            this,
            "Too many failed password attempts!\nPlease wait 15 seconds before trying again.",
            "Account Temporarily Locked",
            JOptionPane.ERROR_MESSAGE
        );

        lockoutTimer = new javax.swing.Timer(1000, (java.awt.event.ActionEvent e) -> {
            countdownSeconds--;
            if (countdownSeconds > 0) {
                logInbtn.setText("Wait (" + countdownSeconds + "s)");
            } else {
                ((javax.swing.Timer) e.getSource()).stop();
                logInbtn.setEnabled(true);
                logInbtn.setBackground(new java.awt.Color(51, 51, 51));
                logInbtn.setText("LOG_IN");
                failedAttempts = 0;
            }
        });
        lockoutTimer.start();
    }

