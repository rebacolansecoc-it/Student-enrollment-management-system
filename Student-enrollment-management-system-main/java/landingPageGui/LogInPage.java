    private void forgetPassBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_forgetPassBtnActionPerformed
       String username = logInUserNameinputtxt.getText().trim();

        if (username.isEmpty()) {
            username = javax.swing.JOptionPane.showInputDialog(
                    this,
                    "Enter your username:",
                    "Forgot Password",
                    javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (username == null || username.trim().isEmpty()) {
                return;
            }
            username = username.trim();
        }

        // Use logInService instance instead of static call
        if (!logInService.usernameExists(username)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Username not found.",
                    "Forgot Password",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String userRole = logInService.getUserRole(username);
        if ("Admin".equalsIgnoreCase(userRole)) {
            String enteredSecretCode = javax.swing.JOptionPane.showInputDialog(
                    this,
                    "Enter Admin Secret Code to verify identity:",
                    "Admin Authorization Required",
                    javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (enteredSecretCode == null || !enteredSecretCode.trim().equals(ADMIN_SECRET_CODE)) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Invalid Admin Secret Code! Password reset denied.",
                        "Access Denied",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );
                return;
            }
        }

        int verificationCode = 1000 + new java.util.Random().nextInt(9000);

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Your 4-digit verification code is:\n\n" + verificationCode + "\n\nEnter this code in the next dialog.",
                "Verification Code",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        String enteredCode = javax.swing.JOptionPane.showInputDialog(
                this,
                "Enter the 4-digit verification code:",
                "Verify Account",
                javax.swing.JOptionPane.QUESTION_MESSAGE
        );

        if (enteredCode == null || !enteredCode.trim().equals(String.valueOf(verificationCode))) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Incorrect verification code.\nPassword was not changed.",
                    "Verification Failed",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        javax.swing.JPasswordField newPasswordField = new javax.swing.JPasswordField();
        javax.swing.JPasswordField confirmPasswordField = new javax.swing.JPasswordField();

        javax.swing.JPanel panel = new javax.swing.JPanel();
        panel.setLayout(new javax.swing.BoxLayout(panel, javax.swing.BoxLayout.Y_AXIS));

        panel.add(new javax.swing.JLabel("Enter new password:"));
        panel.add(newPasswordField);
        panel.add(javax.swing.Box.createVerticalStrut(10));
        panel.add(new javax.swing.JLabel("Confirm new password:"));
        panel.add(confirmPasswordField);

        int result = javax.swing.JOptionPane.showConfirmDialog(
                this,
                panel,
                "Change Password",
                javax.swing.JOptionPane.OK_CANCEL_OPTION,
                javax.swing.JOptionPane.PLAIN_MESSAGE
        );

        if (result != javax.swing.JOptionPane.OK_OPTION) {
            return;
        }

        String newPassword = new String(newPasswordField.getPassword());
        String confirmPassword = new String(confirmPasswordField.getPassword());

        if (newPassword.isEmpty() || !newPassword.equals(confirmPassword)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Passwords cannot be empty and must match.",
                    "Password Warning",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        boolean changed = logInService.changePassword(username, newPassword);

        if (changed) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Password changed successfully!\nYou can now log in with your new password.",
                    "Password Changed",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Password could not be changed.",
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_forgetPassBtnActionPerformed

