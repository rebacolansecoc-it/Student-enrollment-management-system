    private void formSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_formSubmitActionPerformed
        Enrollment existing = enrollmentService.getEnrollmentByStudent(username);
        
        // Removed the deletion logic here so details persist and can be updated seamlessly.

        JTextField firstNameField = new JTextField(existing != null ? existing.getFirstName() : "");
        JTextField lastNameField = new JTextField(existing != null ? existing.getLastName() : "");
        JComboBox<String> genderBox = new JComboBox<>(new String[]{"Male", "Female", "Other"});
        if (existing != null && existing.getGender() != null) genderBox.setSelectedItem(existing.getGender());

        JTextField emailField = new JTextField(existing != null ? existing.getEmail() : username + "@student.edu");
        
        JComboBox<String> gradeBox = new JComboBox<>(new String[]{"1st Year", "2nd Year", "3rd Year", "4th Year"});
        if (existing != null) gradeBox.setSelectedItem(existing.getGradeLevel());

        List<String> courses = enrollmentService.getAvailableCourses();
        JComboBox<String> courseBox = new JComboBox<>(courses.toArray(new String[0]));
        if (existing != null) courseBox.setSelectedItem(existing.getCourseName());

        JComboBox<String> sponsorshipBox = new JComboBox<>(sponsorshipOptions.toArray(new String[0]));
        if (existing != null) sponsorshipBox.setSelectedItem(existing.getSponsorship());

        JPanel panel = new JPanel(new java.awt.GridLayout(0, 1, 5, 5));
        panel.add(new JLabel("First Name:"));
        panel.add(firstNameField);
        panel.add(new JLabel("Last Name:"));
        panel.add(lastNameField);
        panel.add(new JLabel("Gender:"));
        panel.add(genderBox);
        panel.add(new JLabel("Email Address:"));
        panel.add(emailField);
        panel.add(new JLabel("Grade / Year Level:"));
        panel.add(gradeBox);
        panel.add(new JLabel("Course:"));
        panel.add(courseBox);
        panel.add(new JLabel("Sponsorship:"));
        panel.add(sponsorshipBox);

        int result = JOptionPane.showConfirmDialog(this, panel, "Student Enrollment Form", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (result == JOptionPane.OK_OPTION) {
            String firstName = firstNameField.getText().trim();
            String lastName = lastNameField.getText().trim();
            String gender = (String) genderBox.getSelectedItem();
            String email = emailField.getText().trim();
            String grade = (String) gradeBox.getSelectedItem();
            String course = (String) courseBox.getSelectedItem();
            String sponsorship = (String) sponsorshipBox.getSelectedItem();

            if (firstName.isEmpty() || lastName.isEmpty() || email.isEmpty()) {
                JOptionPane.showMessageDialog(this, "First Name, Last Name, and Email cannot be empty!", "Validation Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            String studentId = (existing != null && existing.getStudentId() != null && !existing.getStudentId().isEmpty()) 
                                ? existing.getStudentId() 
                                : enrollmentService.generateNextStudentId();

            // Generate Class Section dynamically based on the chosen course and batch size limits (40 per batch)
            String classSection = (existing != null && existing.getClassSection() != null && existing.getCourseName().equals(course))
                                ? existing.getClassSection() 
                                : enrollmentService.generateNextClassSection(course);
           
            // Resubmitting sets status back to 'Pending'
            Enrollment newEnrollment = new Enrollment(studentId, firstName, lastName, gender, email, grade, course, sponsorship, classSection, "Pending");
            
            boolean success = enrollmentService.saveOrUpdateEnrollment(newEnrollment);
            if (success) {
                JOptionPane.showMessageDialog(this, "Enrollment request submitted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                loadEnrollmentDetails();
            } else {
                JOptionPane.showMessageDialog(this, "Database update failed.", "Submission Failed", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_formSubmitActionPerformed

