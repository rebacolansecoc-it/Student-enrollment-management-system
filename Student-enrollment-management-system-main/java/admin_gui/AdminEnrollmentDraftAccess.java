    // Load declined enrollment records into the table
    private void loadDeclinedDraftsTable() {
        DefaultTableModel model = new DefaultTableModel(
            new Object[][] {},
            new String[] {"ID", "Student Name", "Course", "Year level", "Status"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) { return false; }
        };

        List<Enrollment> drafts = enrollmentService.getDeclinedEnrollmentRequests();
        for (Enrollment enr : drafts) {
            model.addRow(new Object[] {
                enr.getStudentId(),
                enr.getStudentName(),
                enr.getCourseName(),
                enr.getGradeLevel(),
                enr.getStatus()
            });
        }
        enrollmentDraftTbl.setModel(model);
        clearDetails();
    }

    // Reset details panel
    private void clearDetails() {
        selectedStudentId = null;
        reqStudentName.setText("Student_name");
        reqAutoGeneratedStudentId.setText("Student_Id");
        reqGradeLevel.setText("Grade_level");
        reqGenderl.setText("Gender");
        reqCourse.setText("Course");
        reqSponsor.setText("Sponsorship");
        reqAutoGeneratedClassSection.setText("Class_section");
        reqEmailAddress.setText("Email_address");
        reqdateOfEnrollment.setText("N/A");
    }

    // Handle row selection for viewing details
    private void setupTableSelectionListener() {
        enrollmentDraftTbl.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                int selectedRow = enrollmentDraftTbl.getSelectedRow();
                if (selectedRow != -1) {
                    selectedStudentId = (String) enrollmentDraftTbl.getValueAt(selectedRow, 0);
                    Enrollment enr = enrollmentService.getEnrollmentByStudent(selectedStudentId);
                    if (enr != null) {
                        reqStudentName.setText(enr.getStudentName());
                        reqAutoGeneratedStudentId.setText(enr.getStudentId());
                        reqGradeLevel.setText(enr.getGradeLevel());
                        reqGenderl.setText(enr.getGender() != null ? enr.getGender() : "N/A");
                        reqCourse.setText(enr.getCourseName());
                        reqSponsor.setText(enr.getSponsorship());
                        reqAutoGeneratedClassSection.setText(enr.getClassSection());
                        reqEmailAddress.setText(enr.getEmail());
                        reqdateOfEnrollment.setText("Declined Draft");
                    }
                }
            }
        });
    }

