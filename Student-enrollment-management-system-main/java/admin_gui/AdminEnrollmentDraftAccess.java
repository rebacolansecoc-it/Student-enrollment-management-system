    private void enrollmentApproveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_enrollmentApproveActionPerformed
        if (selectedStudentId == null || selectedStudentId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a student draft from the table first.", "Selection Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        boolean success = enrollmentService.updateEnrollmentStatus(selectedStudentId, "Approved");
        if (success) {
            JOptionPane.showMessageDialog(this, "Enrollment draft approved successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadDeclinedDraftsTable();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to approve draft.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_enrollmentApproveActionPerformed

    private void enrollmentDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_enrollmentDeleteActionPerformed
        if (selectedStudentId == null || selectedStudentId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a student draft from the table first.", "Selection Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to permanently delete this record from the database?", "Confirm Permanent Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            boolean success = enrollmentService.deleteEnrollment(selectedStudentId);
            if (success) {
                JOptionPane.showMessageDialog(this, "Enrollment record permanently deleted.", "Success", JOptionPane.INFORMATION_MESSAGE);
                loadDeclinedDraftsTable();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete enrollment record.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_enrollmentDeleteActionPerformed

